import asyncHandler from '../../utils/asyncHandler.js';
import ApiResponse from '../../utils/ApiResponse.js';
import * as svc from './chief-doctor.service.js';
const uid=req=>req.user.id||req.user._id;
const ok=fn=>asyncHandler(async(req,res)=>res.json(new ApiResponse(200,await fn(req))));
export const dashboard=ok(()=>svc.dashboard());
export const doctors=ok(req=>svc.doctors(req.query));
export const departments=ok(()=>svc.departments());
export const appointments=ok(req=>svc.appointments(req.query));
export const reassign=ok(req=>svc.reassignAppointment(req.params.id,req.body,uid(req),req));
export const labs=ok(req=>svc.labResults(req.query));
export const approveLab=ok(req=>svc.approveLab(req.params.id,uid(req)));
export const returnLab=ok(req=>svc.returnLab(req.params.id,req.body.reason,uid(req),req));
export const documents=ok(req=>svc.documents(req.query));
export const reviewDocument=ok(req=>svc.reviewDocument(req.params.kind,req.params.id,req.body,uid(req),req));
export const incidents=ok(req=>svc.incidents(req.query));
export const createIncident=asyncHandler(async(req,res)=>res.status(201).json(new ApiResponse(201,await svc.createIncident(req.body,uid(req),req))));
export const updateIncident=ok(req=>svc.updateIncident(req.params.id,req.body,uid(req),req));
export const councils=ok(req=>svc.councils(req.query));
export const createCouncil=asyncHandler(async(req,res)=>res.status(201).json(new ApiResponse(201,await svc.createCouncil(req.body,uid(req),req))));
export const updateCouncil=ok(req=>svc.updateCouncil(req.params.id,req.body,uid(req),req));
export const reports=ok(req=>svc.reports(req.query));
export const audit=ok(req=>svc.audit(req.query));
