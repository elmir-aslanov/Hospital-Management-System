const SKIP_TAGS = new Set(['SCRIPT', 'STYLE', 'NOSCRIPT', 'TEXTAREA', 'CODE', 'PRE'])
const ATTRS = ['placeholder', 'title', 'aria-label']

function buildReverseMap(lang) {
  const current = TRANSLATIONS[lang] || {}
  const reverse = {}

  for (const map of Object.values(TRANSLATIONS)) {
    for (const [source, translated] of Object.entries(map)) {
      reverse[translated] = source
    }
  }

  for (const source of Object.keys(current)) {
    reverse[source] = source
  }

  return reverse
}

function preserveWhitespace(original, translated) {
  const leading = original.match(/^\s*/)?.[0] || ''
  const trailing = original.match(/\s*$/)?.[0] || ''
  return `${leading}${translated}${trailing}`
}

