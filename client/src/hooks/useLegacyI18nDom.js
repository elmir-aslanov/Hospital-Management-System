function translateText(value, lang, reverse) {
  const trimmed = value.replace(/\s+/g, ' ').trim()
  if (!trimmed) return value

  const source = reverse[trimmed] || trimmed
  const exact = lang === 'az' ? source : TRANSLATIONS[lang]?.[source]
  const translated = exact || translateCountText(source, lang)

  return translated === trimmed ? value : preserveWhitespace(value, translated)
}

function translateNode(node, lang, reverse) {
  if (node.nodeType === Node.TEXT_NODE) {
    const parent = node.parentElement
    if (!parent || SKIP_TAGS.has(parent.tagName)) return
    node.nodeValue = translateText(node.nodeValue || '', lang, reverse)
    return
  }

  if (node.nodeType !== Node.ELEMENT_NODE || SKIP_TAGS.has(node.tagName)) return

  for (const attr of ATTRS) {
    const value = node.getAttribute(attr)
    if (value) node.setAttribute(attr, translateText(value, lang, reverse))
  }
}

function translateTree(root, lang) {
  const reverse = buildReverseMap(lang)
  translateNode(root, lang, reverse)

  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT)
  let node = walker.nextNode()
  while (node) {
    translateNode(node, lang, reverse)
    node = walker.nextNode()
  }
}

export default function useLegacyI18nDom() {
  const { i18n } = useTranslation()

  useEffect(() => {
    let frame = 0

    const run = () => {
      cancelAnimationFrame(frame)
      frame = requestAnimationFrame(() => translateTree(document.body, i18n.language || 'az'))
    }

    run()
    const observer = new MutationObserver(run)
    observer.observe(document.body, {
      childList: true,
      subtree: true,
      characterData: true,
      attributes: true,
      attributeFilter: ATTRS,
    })

    i18n.on('languageChanged', run)

    return () => {
      cancelAnimationFrame(frame)
      observer.disconnect()
      i18n.off('languageChanged', run)
    }
  }, [i18n])
}
